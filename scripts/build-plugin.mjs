/**
 * The build shared by every plugin in the repository: one bundle per plugin, with every package bundled
 * in, the docx library's base64 code removed, and a check that the bundle loads nothing at run time but
 * what Obsidian provides.
 */
import esbuild from 'esbuild';
import { builtinModules } from 'node:module';
import { readFile } from 'node:fs/promises';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

/**
 * Removes the three features of the docx library that use base64 (btoa, atob), none of which the
 * plugin uses: password protection of a document (its hash and salt are base64), the "base64" output
 * format (the plugin packs to an ArrayBuffer) and images given as base64 data URIs (the plugin exports
 * no images; images given as bytes still work). Each now throws if called. The build fails if the
 * library's code has changed, so an upgrade cannot silently bring the calls back.
 */
const DOCX_WITHOUT_BASE64 = [
	[
		'return new Uint8Array(atob(dataURI.substring(base64IndexWithOffset)).split("").map((c) => c.charCodeAt(0)));',
		'throw new Error("Images given as base64 data URIs are not supported by this plugin");',
	],
	[
		'var toBase64 = (bytes) => btoa(String.fromCharCode(...bytes));',
		'var toBase64 = () => { throw new Error("Document protection is not supported by this plugin"); };',
	],
	[
		'base64: (data) => btoa(binaryStringOf(data)),',
		'base64: () => { throw unsupported("base64"); },',
	],
];
const removeBase64 = {
	name: 'docx-without-base64',
	setup(build) {
		build.onLoad({ filter: /[\\/]node_modules[\\/]docx[\\/]dist[\\/]index\.(?:mjs|cjs)$/ }, async (args) => {
			let code = await readFile(args.path, 'utf8');
			for (const [from, to] of DOCX_WITHOUT_BASE64) {
				if (!code.includes(from)) throw new Error(`docx-without-base64: "${from}" not found in ${args.path}; the docx library has changed.`);
				code = code.split(from).join(to);
			}
			if (/\b(?:btoa|atob)\s*\(/.test(code)) throw new Error(`docx-without-base64: base64 call remains in ${args.path}.`);
			return { contents: code, loader: 'js' };
		});
	},
};

/**
 * Every plugin is standalone: everything it needs is bundled into its main.js, and at run time it loads
 * only what Obsidian provides. Any other module (an unbundled package, or another plugin such as Legal
 * Core) fails the build. AGLC4 Citations in particular must work without Legal Core.
 */
export const PROVIDED_BY_OBSIDIAN = new Set(['obsidian', '@codemirror/state', '@codemirror/view']);
function checkStandalone(name, metafile) {
	const loaded = new Set();
	for (const output of Object.values(metafile.outputs)) {
		for (const i of output.imports) if (i.external) loaded.add(i.path);
	}
	const extra = [...loaded].filter((m) => !PROVIDED_BY_OBSIDIAN.has(m));
	if (extra.length > 0) {
		throw new Error(`${name} must be standalone, but its main.js would load: ${extra.join(', ')}. Bundle these instead.`);
	}
}

/** An esbuild context for one plugin. */
export function pluginContext({ entry, outfile, prod }) {
	return esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: [entry],
	bundle: true,
	plugins: [removeBase64],
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile,
	// Not minified, so the released main.js can be read and reviewed.
	minify: false,
	metafile: true,
});
}

/** Build every plugin once, failing on anything that is not standalone. */
export async function buildAll(plugins) {
	for (const p of plugins) {
		const ctx = await pluginContext({ ...p, prod: true });
		const result = await ctx.rebuild();
		checkStandalone(p.name, result.metafile);
		await ctx.dispose();
	}
}

/** Rebuild every plugin on change. */
export async function watchAll(plugins) {
	for (const p of plugins) await (await pluginContext({ ...p, prod: false })).watch();
}
